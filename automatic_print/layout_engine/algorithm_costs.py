"""Audited complexity descriptions, not measured operation counters."""
VARIABLES = ('n：图片数；g：订单/尺码组数；k：非等价刀位候选数；'
             'b：同尺码等价几何桶数；P：解码/处理像素量；c：透明空间候选数；W：整数位集合的机器字宽。')
STEPS = (
    ('文件排序与订单归组', '通常 O(n log n)', '按身份归组及排序；不读取整张图', '已按字典归组'),
    ('尺寸、膜标签与刀码测量', '缓存命中 O(n)元数据检查；未命中另计像素', '持久化整批结果命中不测量；未命中O(P+c+文字渲染)', '最多4路；两方向共享解码；跨重启缓存'),
    ('刀位候选去重', '排序 O(n log n)，另有位集合成本', '边界扫描；大整数操作/哈希随 n/W 增长，不能当作严格常数', '已取消每候选全图逐项判断'),
    ('单件同尺码配对', 'O(n × b)，最坏 O(n²)', '每张只查各等价几何桶首个有效成员；保留原贪心及平局顺序', '重复尺寸分桶；不再移动剩余列表'),
    ('固定顺序排版', '通常 O(n)', '动态规划只比较当前组与相邻组；组内处理另计', '不等于整个自动排版线性'),
    ('自动刀位整体比较', 'O(k × n × b)，最坏 O(k × n²)', '各刀位执行等价分桶配对与排版；k 和 b 可能随 n 增长', '同膜宽旋转方案复用常规基准'),
    ('旋转区完整订单分配', '纯单件筛选 O(n)；多件最坏 O(k × g²)', '纯单件复用常规双排，只累计比较完整单排尺码后缀；多件另计位集合成本', '单件不再搜索旋转刀位组合；多件算法未改'),
    ('坐标与订单安全检查', '按校验器及分组规模变化', '整数坐标、顺序、刀位；不等同全图像素扫描', '独立校验防止规划/合成错误'),
    ('透明区与输出通道检查', 'O(实际扫描像素量)', '同矩形测量缓存复用；最终结果检查实际像素', '范围可行不能替代覆盖检测'),
    ('图片准备、合成与保存', '主要 O(P)', 'PNG压缩、磁盘速度、像素量及线程调度影响常数', '图片/分段/批次可并行；同画布有序写入'),
    ('批次总结', '固定双列 O(n)；一般 O(n + E)', '一次建立图片归属与区域/行索引；E为同行订单关系数', '已取消逐订单全批扫描；伙伴按生产顺序展示'),
)
